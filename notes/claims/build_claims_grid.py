#!/usr/bin/env python3
"""Builds the claims ledger views from the three data files beside it (methods.csv, claims.csv, cells.csv; '|'-separated).
Marks: X done and good; X* done, the method failed and was superseded for it; S method superseded before it was run; O to do;
N the method does not apply (the default for every cell not listed in cells.csv).
Reads also needs_backing.txt (free text, printed as section 4).
Outputs: ../2026-11-10_claims_ledger.md (three views) and grid.csv (the grid alone, for a spreadsheet).
Run from this folder:  python3 build_claims_grid.py"""
import csv, os, sys, collections
if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    def rd(f):
        lines = open(os.path.join(here, f), encoding='utf-8').read().splitlines()
        head = lines[0].split('|'); out = []
        for n, line in enumerate(lines[1:], 2):
            parts = line.split('|')
            assert len(parts) == len(head), f"{f} line {n}: {len(parts)} fields, expected {len(head)} (a stray '|' inside a field?)"
            out.append(dict(zip(head, parts)))
        return out
    methods, claims, cells = rd('methods.csv'), rd('claims.csv'), rd('cells.csv')
    mid = {m['id']: m for m in methods}; cid = {c['id']: c for c in claims}
    cell = {}
    for r in cells:
        assert r['claim'] in cid, r; assert r['method'] in mid, r; assert r['mark'] in ('X', 'X*', 'S', 'O'), r
        assert (r['claim'], r['method']) not in cell, r
        cell[(r['claim'], r['method'])] = r
    first = {}
    for i, c in enumerate(claims):
        first.setdefault((c['paper'], c['year']), i)
    claims.sort(key=lambda c: (int(c['year']), first[(c['paper'], c['year'])]))          # by year, then papers in file order, claims in file order
    years = [int(m['year']) for m in methods]
    assert years == sorted(years), "methods.csv must be in order of year (columns run earliest to latest)"
    for grp in {c['merged'] for c in claims}:
        assert len({c['claim'] for c in claims if c['merged'] == grp}) == 1, f"merged group {grp}: the wordings differ"
    eras = []
    for m in methods:
        if m['era'] not in eras:
            eras.append(m['era'])
    L = []
    L.append("# Claims ledger: what each paper set out to show, and by which methods it has been shown here (10 Nov 2026)\n")
    L.append("Generated by `notes/claims/build_claims_grid.py` from `methods.csv`, `claims.csv`, `cells.csv` — edit those, not this file.")
    L.append("Marks: **X** the method was carried through and its answer can be trusted; **X\\*** carried through, the method failed and was")
    L.append("superseded for it; **S** superseded before it was run; **O** to do; **N** does not apply. A mark is about the method. Whether the")
    L.append("paper's claim held is the **verdict** beside each paper in section 2. Papers in order of publication throughout (author, 10 Nov).")
    L.append("\"Method P\" and \"method M\" are not used here: they name Feynman parameters with the average continuation and momentum-space")
    L.append("residues in `bubble/`, and were reused in rung 3 for DeWitt's recursion and the (3.40) formula.\n")
    L.append("## 1. By paper\n")
    last = None
    for c in claims:
        key = (c['paper'], c['year'])
        if key != last:
            L.append(f"\n**{c['paper']} {c['year']}** — source: {c['source']}\n"); last = key
        L.append(f"- `{c['id']}` {c['claim']}")
    L.append("\n## 2. Deduplicated, by kind; under each, the methods\n")
    kinds = []
    for c in claims:
        if c['kind'] not in kinds:
            kinds.append(c['kind'])
    for k in sorted(kinds):
        L.append(f"\n### {k}\n")
        groups = collections.OrderedDict()
        for c in claims:
            if c['kind'] == k:
                groups.setdefault(c['merged'], []).append(c)
        for g, cs in sorted(groups.items(), key=lambda kv: kv[1][0]['claim']):
            L.append(f"- **{cs[0]['claim']}**")
            L.append("  - papers: " + "; ".join(f"{c['paper']} {c['year']} (`{c['id']}`): {c['verdict']}" for c in cs))
            for m in methods:
                for c in cs:
                    if (c['id'], m['id']) in cell:
                        r = cell[(c['id'], m['id'])]
                        L.append(f"  - {r['mark']} — {m['name']} ({m['year']})" + (f" [`{c['id']}`]" if len(cs) > 1 else "") + f": {r['evidence']}")
    L.append("\n## 3. The grid\n")
    L.append("Rows: (paper, claim), papers in order of publication. Columns: methods, grouped by era, earliest at the left.\n")
    L.append("Column key: " + "; ".join(f"**{m['id']}** = {m['name']} ({m['year']})" for m in methods) + "\n")
    L.append("| paper, claim | " + " | ".join(m['id'] for m in methods) + " |")
    L.append("|---|" + "|".join(":-:" for _ in methods) + "|")
    L.append("| *era* | " + " | ".join(f"*{m['era']}*" for m in methods) + " |")
    rows = [["", ""] + [m['era'] for m in methods], ["paper", "claim"] + [f"{m['name']} ({m['year']})" for m in methods]]
    counts = collections.Counter()
    for c in claims:
        marks = [cell[(c['id'], m['id'])]['mark'] if (c['id'], m['id']) in cell else 'N' for m in methods]
        counts.update(marks)
        L.append(f"| {c['paper']} {c['year']}, `{c['id']}` | " + " | ".join(x.replace('*', '\\*') if x != 'N' else '·' for x in marks) + " |")
        rows.append([f"{c['paper']} {c['year']}", f"{c['id']} {c['claim']}"] + marks)
    L.append("\n(· stands for N, to keep the marks visible.)\n")
    L.append(f"Counts: X {counts['X']}, X* {counts['X*']}, S {counts['S']}, O {counts['O']}, N {counts['N']}; {len(claims)} claims, {len(methods)} methods.")
    L.append("\n## 4. Needing backing\n")
    L.append(open(os.path.join(here, 'needs_backing.txt'), encoding='utf-8').read())
    open(os.path.join(here, '..', '2026-11-10_claims_ledger.md'), 'w', encoding='utf-8').write("\n".join(L) + "\n")
    with open(os.path.join(here, 'grid.csv'), 'w', newline='', encoding='utf-8-sig') as f:
        csv.writer(f, lineterminator='\n').writerows(rows)
    print(f"claims {len(claims)}, methods {len(methods)}, cells listed {len(cell)}: X {counts['X']}, X* {counts['X*']}, S {counts['S']}, O {counts['O']}, N {counts['N']}")
